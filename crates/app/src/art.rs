/// Renders a text grid to RGBA, `scale` screen pixels per art pixel.
/// `color(ch, x, width)` returns the pixel color, or None for transparent.
pub fn render(rows: &[&str], scale: usize, color: impl Fn(char, usize, usize) -> Option<[u8; 4]>) -> (u32, u32, Vec<u8>) {
    let h = rows.len();
    let w = rows.iter().map(|r| r.chars().count()).max().unwrap_or(0);
    let (pw, ph) = (w * scale, h * scale);
    let mut buf = vec![0u8; pw * ph * 4];
    for (y, row) in rows.iter().enumerate() {
        for (x, ch) in row.chars().enumerate() {
            let Some(c) = color(ch, x, w) else { continue };
            for dy in 0..scale {
                for dx in 0..scale {
                    let i = ((y * scale + dy) * pw + (x * scale + dx)) * 4;
                    buf[i..i + 4].copy_from_slice(&c);
                }
            }
        }
    }
    (pw as u32, ph as u32, buf)
}

/// The mark's colors: lit left half, shaded right half, `core` in the center.
pub fn mark_color(hi: [u8; 4], lo: [u8; 4], core: Option<[u8; 4]>) -> impl Fn(char, usize, usize) -> Option<[u8; 4]> {
    move |ch, x, w| match ch {
        '#' => Some(if x < w / 2 { hi } else { lo }),
        'o' => core,
        _ => None,
    }
}

pub fn wordmark_rows() -> Vec<String> {
    let mut rows = vec![String::new(); 7];
    for (i, c) in "hexward".chars().enumerate() {
        let glyph = GLYPHS.iter().find(|g| g.0 == c).map(|g| g.1).unwrap_or(GLYPHS[0].1);
        for (y, r) in glyph.iter().enumerate() {
            if i > 0 {
                rows[y].push('.');
            }
            rows[y].push_str(r);
        }
    }
    rows
}
